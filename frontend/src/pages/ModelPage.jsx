import { useEffect, useState } from 'react'
import { api } from '../api.js'
import { pct } from '../format.js'
import RatingBadge from '../components/RatingBadge.jsx'

const LABELS = {
  avg_dbt: 'Average days beyond terms', latest_dbt: 'Days beyond terms, last 3 months',
  dbt_change_3m: '3-month change in days beyond terms', log_total_outstanding: 'Total outstanding (log)',
  n_suppliers: 'Number of suppliers', outstanding_growth_6m: 'Outstanding growth, 6 months',
  share_overdue: 'Share of dues overdue', largest_supplier_share: 'Largest single-supplier share',
}

function Confusion({ m }) {
  const [[tn, fp], [fn, tp]] = m
  const max = Math.max(tn, fp, fn, tp)
  const cell = (v, good) => (
    <td style={{ background: good ? `rgba(29,92,58,${0.1 + 0.6 * v / max})` : `rgba(192,57,43,${v ? 0.15 + 0.5 * v / max : 0.04})` }}>{v}</td>
  )
  return (
    <table className="confusion">
      <thead><tr><th></th><th>Predicted: no default</th><th>Predicted: default</th></tr></thead>
      <tbody>
        <tr><th>Actual: no default</th>{cell(tn, true)}{cell(fp, false)}</tr>
        <tr><th>Actual: default</th>{cell(fn, false)}{cell(tp, true)}</tr>
      </tbody>
    </table>
  )
}

export default function ModelPage({ onRegenerated }) {
  const [m, setM] = useState(null)
  const [busy, setBusy] = useState(false)

  useEffect(() => { api.metrics().then(setM) }, [])

  const regenerate = async () => {
    setBusy(true)
    try {
      const r = await api.regenerate()
      setM(r.metrics)
      onRegenerated()
    } finally {
      setBusy(false)
    }
  }

  if (!m) return <p className="muted">Loading metrics…</p>

  return (
    <>
      <h1>Model</h1>
      <div className="note">
        <strong>Synthetic data.</strong> All suppliers, dealers and invoices are generated by
        <code> backend/generate_data.py</code> with a fixed seed. The model learns from months 1-18 and
        predicts defaults in months 19-24. Because the data is simulated, scores are far higher than real life.
      </div>

      <div className="grid2">
        {m.models.map((r) => (
          <div className="card" key={r.model}>
            <h3>{r.model} {r.model === m.chosen_model && <span className="pill">chosen</span>}</h3>
            <div className="tiles inline">
              <div className="tile"><span>ROC-AUC</span><strong>{r.roc_auc.toFixed(3)}</strong></div>
              <div className="tile"><span>Accuracy</span><strong>{pct(r.accuracy)}</strong></div>
            </div>
            <Confusion m={r.confusion_matrix} />
            <p className="muted small">Test set of {m.test_rows} dealers, threshold: defaulting probability ≥ {m.threshold}.</p>
          </div>
        ))}
      </div>

      <div className="grid2">
        <div className="card">
          <h3>Logistic regression coefficients <span className="muted small">on standardised features</span></h3>
          <table className="table">
            <tbody>
              {Object.entries(m.coefficients).sort((a, b) => b[1] - a[1]).map(([k, v]) => (
                <tr key={k}><td>{LABELS[k] || k}</td><td className={`num ${v > 0 ? 'neg' : 'pos'}`}>{v > 0 ? '+' : ''}{v.toFixed(2)}</td></tr>
              ))}
            </tbody>
          </table>
          <p className="muted small">{m.why} Training rows: {m.train_rows}; default rate {pct(m.default_rate)}.</p>
        </div>
        <div className="card">
          <h3>Rating cut-offs</h3>
          <table className="table">
            <thead><tr><th>Rating</th><th className="num">Defaulting probability below</th></tr></thead>
            <tbody>
              {m.rating_cutoffs.map((c) => (
                <tr key={c.rating}><td><RatingBadge rating={c.rating} /></td><td className="num">{c.pd_below > 1 ? '100%' : pct(c.pd_below, 2)}</td></tr>
              ))}
            </tbody>
          </table>
          <p className="muted small">Any invoice 90+ days past due puts a dealer at D.</p>
        </div>
      </div>

      <div className="card">
        <h3>Data controls</h3>
        <button className="btn" onClick={regenerate} disabled={busy}>
          {busy ? 'Regenerating… (about 20 seconds)' : 'Regenerate data & retrain'}
        </button>
      </div>
    </>
  )
}
